// Renders the Kaveyl logo (apps/web/src/logo.ts) into the favicon, the PNG icons of the web app
// manifest (apps/web/public) and the logo of the mails (apps/server/src/mail/logo.ts, embedded PNG).
// Run once after changing the logo: node scripts/make-icons.mjs
import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { logoSvg } from '../apps/web/src/logo.ts';

const PUB = resolve(import.meta.dirname, '../apps/web/public');
writeFileSync(join(PUB, 'favicon.svg'), logoSvg({ small: true }) + '\n');

// iOS and Android cut the shape themselves: a full square without transparency. Maskable icons keep
// the drawing inside the safe zone (circle of 80 %), hence smaller.
const icons = [
  ['icon-192.png', 192, {}],
  ['icon-512.png', 512, {}],
  ['icon-maskable-512.png', 512, { rx: 0, scale: 0.74 }],
  ['apple-touch-icon.png', 180, { rx: 0 }],
];

const browser = await chromium.launch();
const page = await browser.newPage();
for (const [name, size, opts] of icons) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<style>html,body{margin:0;background:transparent}</style><img src="data:image/svg+xml,${encodeURIComponent(logoSvg(opts))}" width="${size}" height="${size}">`);
  writeFileSync(join(PUB, 'icons', name), await page.screenshot({ omitBackground: true }));
  console.log(name);
}
// Mails show the logo at 26 px – the small drawing, rendered at three times the size for sharp displays.
await page.setViewportSize({ width: 78, height: 78 });
await page.setContent(`<style>html,body{margin:0;background:transparent}</style><img src="data:image/svg+xml,${encodeURIComponent(logoSvg({ small: true }))}" width="78" height="78">`);
const mailLogo = (await page.screenshot({ omitBackground: true })).toString('base64');
writeFileSync(
  resolve(import.meta.dirname, '../apps/server/src/mail/logo.ts'),
  `// Generated by scripts/make-icons.mjs from apps/web/src/logo.ts – do not edit.\n/** The logo for mails: PNG (78 × 78, shown at 26 px), base64. */\nexport const MAIL_LOGO_PNG = '${mailLogo}';\n`,
);
await browser.close();
console.log('favicon.svg, mail/logo.ts');
